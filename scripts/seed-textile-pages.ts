async function main() {
  const payload = await getPayload({ config });

  for (const item of ITEMS) {
    const existing = await payload.find({
      collection: 'textile-pages',
      where: { slug: { equals: item.slug } },
      limit: 1,
    });

    if (existing.docs.length > 0) {
      console.log(`skip: "${item.slug}" already exists (id=${existing.docs[0].id})`);
      continue;
    }

    const created = await payload.create({
      collection: 'textile-pages',
      data: item,
    });
    console.log(`created: "${item.slug}" (id=${created.id})`);
  }

  process.exit(0);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
