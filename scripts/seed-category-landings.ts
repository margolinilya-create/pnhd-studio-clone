// ───────────────────────────────────────────────────────────────────────────
// Lexical helpers — build minimal SerializedEditorState manually. Source
// configs use only paragraphs / headings (h2) / ul / ol with text-only items.
// No bold / italic / links / images, so we stay schema-thin.

type LexicalText = {
  type: 'text';
  version: 1;
  detail: 0;
  format: 0;
  mode: 'normal';
  style: '';
  text: string;
};

type LexicalParagraph = {
  type: 'paragraph';
  version: 1;
  direction: 'ltr';
  format: '';
  indent: 0;
  textFormat: 0;
  textStyle: '';
  children: LexicalText[];
};

type LexicalHeading = {
  type: 'heading';
  tag: 'h2' | 'h3';
  version: 1;
  direction: 'ltr';
  format: '';
  indent: 0;
  children: LexicalText[];
};

type LexicalListItem = {
  type: 'listitem';
  version: 1;
  direction: 'ltr';
  format: '';
  indent: 0;
  value: number;
  children: LexicalText[];
};

type LexicalList = {
  type: 'list';
  version: 1;
  direction: 'ltr';
  format: '';
  indent: 0;
  listType: 'bullet' | 'number';
  start: 1;
  tag: 'ul' | 'ol';
  children: LexicalListItem[];
};

type LexicalBlock = LexicalParagraph | LexicalHeading | LexicalList;

const textNode = (text: string): LexicalText => ({
  type: 'text',
  version: 1,
  detail: 0,
  format: 0,
  mode: 'normal',
  style: '',
  text,
});

const p = (text: string): LexicalParagraph => ({
  type: 'paragraph',
  version: 1,
  direction: 'ltr',
  format: '',
  indent: 0,
  textFormat: 0,
  textStyle: '',
  children: [textNode(text)],
});

const h2 = (text: string): LexicalHeading => ({
  type: 'heading',
  tag: 'h2',
  version: 1,
  direction: 'ltr',
  format: '',
  indent: 0,
  children: [textNode(text)],
});

const li = (text: string, value = 1): LexicalListItem => ({
  type: 'listitem',
  version: 1,
  direction: 'ltr',
  format: '',
  indent: 0,
  value,
  children: [textNode(text)],
});

const ul = (items: string[]): LexicalList => ({
  type: 'list',
  version: 1,
  direction: 'ltr',
  format: '',
  indent: 0,
  listType: 'bullet',
  start: 1,
  tag: 'ul',
  children: items.map((t, i) => li(t, i + 1)),
});

const ol = (items: string[]): LexicalList => ({
  type: 'list',
  version: 1,
  direction: 'ltr',
  format: '',
  indent: 0,
  listType: 'number',
  start: 1,
  tag: 'ol',
  children: items.map((t, i) => li(t, i + 1)),
});

const lexicalRoot = (children: LexicalBlock[]) => ({
  root: {
    type: 'root',
    version: 1,
    direction: 'ltr' as const,
    format: '' as const,
    indent: 0,
    children,
  },
});

// ───────────────────────────────────────────────────────────────────────────
// HTML entities → text (no HTML escaping in Lexical text node — it's serialized as plain string).

const DECODE = (s: string): string =>
  s
    .replace(/&mdash;/g, '—')
    .replace(/&nbsp;/g, ' ')
    .replace(/&amp;/g, '&');

