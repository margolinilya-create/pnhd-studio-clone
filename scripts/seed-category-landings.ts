async function main() {
  const payload = await getPayload({ config });

  for (const data of LANDINGS) {
    const existing = await payload.find({
      collection: 'categories',
      where: { slug: { equals: data.slug } },
      limit: 1,
    });

    const payloadData = {
      name: data.name,
      slug: data.slug,
      h1: data.h1,
      metaTitle: data.metaTitle,
      metaDescription: data.metaDescription,
      productType: data.productType,
      faqSet: data.faqSet,
      bodyContent: data.bodyContent,
      isLanding: true,
      _status: 'published' as const,
    };

    if (existing.docs.length > 0) {
      const id = existing.docs[0].id;
      const updated = await payload.update({
        collection: 'categories',
        id,
        data: payloadData as Parameters<typeof payload.update>[0]['data'],
      });
      console.log(`[seed-category-landings] Updated /${data.slug} (id=${updated.id})`);
    } else {
      const created = await payload.create({
        collection: 'categories',
        data: payloadData as Parameters<typeof payload.create>[0]['data'],
      });
      console.log(`[seed-category-landings] Created /${data.slug} (id=${created.id})`);
    }
  }

  process.exit(0);
}

main().catch((err) => {
  console.error('[seed-category-landings] Failed:', err);
  process.exit(1);
});
